func TestToBuck2ConfigRejectsUnusableTokens(t *testing.T) {
	t.Parallel()

	base, err := buck2CacheOnlySetup("grpcs://ingress.example:443", "")
	if err != nil {
		t.Fatalf("buck2CacheOnlySetup: %v", err)
	}

	for _, token := range []string{"tok,123", "tok$HOME", "tok\n123", "tok\r123"} {
		out := base
		out.StaticToken = token

		if _, err := toBuck2Config(out); err == nil {
			t.Errorf("expected token %q to be rejected", token)
		}
	}

	out := base
	out.StaticToken = "tok-123_abc.def$"
	if _, err := toBuck2Config(out); err != nil {
		t.Errorf("token with a trailing dollar sign is safe, but was rejected: %v", err)
	}

	out.TLSClientCert = "/tmp/client.pem"
	if _, err := toBuck2Config(out); err == nil || !strings.Contains(err.Error(), "both static and mTLS") {
		t.Errorf("configuration with conflicting credentials returned %v", err)
	}
}

func TestIssueBuck2Token(t *testing.T) {
	t.Parallel()

	source := &buck2TestTokenSource{token: "tok123"}
	out := buck2Setup{}
	if err := issueBuck2Token(context.Background(), source, 90*time.Minute, &out); err != nil {
		t.Fatalf("issueBuck2Token: %v", err)
	}
	if source.dur != 90*time.Minute || source.force {
		t.Fatalf("IssueToken called with (%s, %t), want (90m, false)", source.dur, source.force)
	}
	if out.StaticToken != "tok123" || out.TokenDuration != 90*time.Minute {
		t.Fatalf("setup token fields = (%q, %s), want (tok123, 90m)", out.StaticToken, out.TokenDuration)
	}

	source = &buck2TestTokenSource{err: errors.New("no token")}
	if err := issueBuck2Token(context.Background(), source, time.Hour, &buck2Setup{}); err == nil || !strings.Contains(err.Error(), "failed to issue bearer token") {
		t.Fatalf("issueBuck2Token error = %v, want wrapped source error", err)
	}

	source = &buck2TestTokenSource{token: "bad,token"}
	if err := issueBuck2Token(context.Background(), source, time.Hour, &buck2Setup{}); err == nil || !strings.Contains(err.Error(), "cannot carry") {
		t.Fatalf("issueBuck2Token error = %v, want invalid header error", err)
	}
}

