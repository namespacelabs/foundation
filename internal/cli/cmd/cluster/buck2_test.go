func TestBuck2ReadinessConfig(t *testing.T) {
	t.Parallel()

	static, cleanup, err := buck2ReadinessConfig("grpcs://cache.example", buck2Setup{StaticToken: "token"})
	if err != nil {
		t.Fatalf("buck2ReadinessConfig(static): %v", err)
	}
	defer cleanup()
	if static.bearerToken != "token" || static.clientCert != "" || static.clientKey != "" {
		t.Fatalf("static readiness config = %#v", static)
	}

	identity := []byte("certificate\nprivate-key")
	mtls, cleanup, err := buck2ReadinessConfig("grpcs://cache.example", buck2Setup{clientIdentity: identity})
	if err != nil {
		t.Fatalf("buck2ReadinessConfig(mTLS): %v", err)
	}
	defer cleanup()
	if mtls.clientCert == "" || mtls.clientCert != mtls.clientKey || mtls.bearerToken != "" {
		t.Fatalf("mTLS readiness config = %#v", mtls)
	}
	assertCredentialFile(t, mtls.clientCert, string(identity))
}

func TestValidateBuck2SetupFlags(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct {
		name         string
		output       string
		tokenDur     time.Duration
		instanceName string
		wantErr      string
	}{
		{name: "plain", output: "plain", tokenDur: time.Hour},
		{name: "json", output: "json", tokenDur: time.Hour},
		{name: "bad output", output: "yaml", tokenDur: time.Hour, wantErr: "unsupported output format"},
		{name: "zero duration", output: "plain", wantErr: "must be greater than zero"},
		{name: "negative duration", output: "plain", tokenDur: -time.Second, wantErr: "must be greater than zero"},
		{name: "instance injection", output: "plain", tokenDur: time.Hour, instanceName: "main\n[other]", wantErr: "must not contain a newline"},
		{name: "instance environment expansion", output: "plain", tokenDur: time.Hour, instanceName: "$HOME", wantErr: "would expand as an environment variable"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := validateBuck2SetupFlags(tc.output, tc.tokenDur, tc.instanceName)
			if tc.wantErr == "" {
				if err != nil {
					t.Fatalf("validateBuck2SetupFlags() error = %v", err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("validateBuck2SetupFlags() error = %v, want error containing %q", err, tc.wantErr)
			}
		})
	}
}

func TestBuck2CommandTree(t *testing.T) {
	t.Parallel()

	for _, path := range [][]string{{"setup"}, {"cache", "setup"}} {
		cmd, args, err := NewBuck2Cmd().Find(path)
		if err != nil {
			t.Fatalf("Find(%v): %v", path, err)
		}
		if len(args) != 0 || cmd.Name() != "setup" {
			t.Fatalf("Find(%v) = (%q, %v), want setup with no remaining args", path, cmd.Name(), args)
		}
		if cmd.Flag("buckconfig") == nil || cmd.Flag("static") == nil || cmd.Flag("static_token_duration") == nil {
			t.Fatalf("Find(%v) is missing Buck2 setup flags", path)
		}
	}

	cmd, args, err := NewBuck2CacheCmd().Find([]string{"setup"})
	if err != nil || len(args) != 0 || cmd.Name() != "setup" {
		t.Fatalf("cache alias Find(setup) = (%q, %v, %v)", cmd.Name(), args, err)
	}
}

