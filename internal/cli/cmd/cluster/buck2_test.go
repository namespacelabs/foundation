func TestEmitBuck2MTLSConfig(t *testing.T) {
	t.Parallel()

	configPath := filepath.Join(t.TempDir(), ".buckconfig.local")
	out, err := buck2CacheOnlySetup("grpcs://cache.example:443", "")
	if err != nil {
		t.Fatalf("buck2CacheOnlySetup: %v", err)
	}
	out.clientIdentity = []byte("certificate\nprivate-key")
	out.serverCAPem = []byte("ca-certificate")

	if err := emitBuck2Config(context.Background(), out, configPath, "json", "remote cache"); err != nil {
		t.Fatalf("emitBuck2Config: %v", err)
	}

	identityPath, err := filepath.Abs(configPath + ".tls.pem")
	if err != nil {
		t.Fatalf("filepath.Abs: %v", err)
	}
	caPath, err := filepath.Abs(configPath + ".ca.pem")
	if err != nil {
		t.Fatalf("filepath.Abs: %v", err)
	}
	assertCredentialFile(t, identityPath, "certificate\nprivate-key")
	assertCredentialFile(t, caPath, "ca-certificate")

	config, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatalf("ReadFile(config): %v", err)
	}
	for _, want := range []string{
		"tls_ca_certs = " + caPath + "\n",
		"tls_client_cert = " + identityPath + "\n",
	} {
		if !strings.Contains(string(config), want) {
			t.Errorf("config %q does not contain %q", config, want)
		}
	}
}

func assertCredentialFile(t *testing.T, path, want string) {
	t.Helper()

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	if string(got) != want {
		t.Errorf("content = %q, want %q", got, want)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("Stat: %v", err)
	}
	if got := info.Mode().Perm(); got != 0600 {
		t.Errorf("permissions = %#o, want 0600", got)
	}
}
